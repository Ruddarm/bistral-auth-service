-- 5. CREATE ALL RESOURCE-ACTION MAPPINGS
-- 5 Resources x 4 Actions = 20 mappings
-- =========================================================

INSERT INTO resource_action_mapping (
    resource_action_mapping_id,
    resource_id,
    action_id,
    is_system_specific,
    created_by
)
SELECT
    (
        MD5(r.resource_id::TEXT || ':' || a.action_id::TEXT)
    )::UUID,
    r.resource_id,
    a.action_id,

    CASE
        WHEN r.resource_name = 'Tenant'
        THEN TRUE
        ELSE FALSE
    END,

    '00000000-0000-0000-0000-000000000001'

FROM resource r
CROSS JOIN actions a

WHERE r.resource_id IN (
    '10000000-0000-0000-0000-000000000001',
    '10000000-0000-0000-0000-000000000002',
    '10000000-0000-0000-0000-000000000003',
    '10000000-0000-0000-0000-000000000004',
    '10000000-0000-0000-0000-000000000005'
)

AND a.action_id IN (
    '20000000-0000-0000-0000-000000000001',
    '20000000-0000-0000-0000-000000000002',
    '20000000-0000-0000-0000-000000000003',
    '20000000-0000-0000-0000-000000000004'
)

ON CONFLICT DO NOTHING;
